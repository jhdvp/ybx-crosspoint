"""Rasterize the existing YBX mark into the firmware's 120px 1-bit bitmap.

Geometry matches src/images/logo.svg and the website's BrandMark component.
The checked-in PNG and header are generated together; no font or network input.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]


def generate():
    scale = 15
    image = Image.new('1', (32 * scale, 32 * scale), 1)
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((scale, scale, 31 * scale - 1, 31 * scale - 1), radius=7 * scale, fill=0)
    for x, y, width, height in ((7, 8.5, 18, 3.4), (7, 14.3, 18, 3.4), (7, 20.1, 11, 3.4)):
        draw.rounded_rectangle((round(x * scale), round(y * scale), round((x + width) * scale) - 1,
                                round((y + height) * scale) - 1), radius=round(height * scale / 2), fill=1)
    image = image.convert('L').resize((120, 120), Image.Resampling.LANCZOS).point(lambda p: 255 if p >= 128 else 0, '1')
    image.save(ROOT / 'src/images/Logo120.png')
    data = image.tobytes()
    assert len(data) == 120 * 120 // 8
    lines = [', '.join(f'0x{b:02x}' for b in data[i:i + 20]) + ',' for i in range(0, len(data), 20)]
    (ROOT / 'src/images/Logo120.h').write_text('#pragma once\n#include <cstdint>\n\n'
        '// Generated by scripts/generate_ybx_logo.py; 120x120, 1-bit, MSB first.\n'
        'static const uint8_t Logo120[] = {\n' + '\n'.join('    ' + line for line in lines) + '\n};\n')


if __name__ == '__main__':
    generate()
