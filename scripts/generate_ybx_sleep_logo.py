"""Generate an E-Ink four-tone YBX Companion sleep logo.

Based on YBX_Branding/src/components/YbxLogo.tsx ('companion' variant):
round badge, two full bars, short accent bar, ring and sensor dot.
0=black through 3=white, two bits/pixel. Supersampled for clean radii.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SIZE = 192
AA = 4
def scaled(v): return round(v * SIZE * AA / 400)

def rounded(draw, box, radius, shade):
    draw.rounded_rectangle(tuple(scaled(v) for v in box), radius=scaled(radius), fill=shade)
def circle(draw, cx, cy, r, shade):
    draw.ellipse(tuple(scaled(v) for v in (cx-r, cy-r, cx+r, cy+r)), fill=shade)

def generate():
    # Visual tones: black sleep background; dark neutral card (1), light
    # graphite accent (2), bright paper strokes (3). No color/ordered dither.
    big = Image.new('L', (SIZE*AA, SIZE*AA), 0)
    d = ImageDraw.Draw(big)
    rounded(d, (14, 14, 386, 386), 72, 85)  # 1: dark graphite card
    # Subtle high-contrast frame; preserves the rounded YBX silhouette
    rounded(d, (22, 22, 378, 378), 66, 78)
    rounded(d, (85, 120, 315, 164), 22, 255)
    rounded(d, (85, 186, 315, 230), 22, 255)
    rounded(d, (85, 252, 225, 296), 22, 170)  # 2: accent
    circle(d, 273, 274, 22, 255)
    circle(d, 273, 274, 14, 78)
    circle(d, 273, 274, 7, 170)
    down = big.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    # Four native gray levels. AA is for edge coverage, not spatial dithering.
    quantized = down.point(lambda p: min(3, (p + 42) // 85))
    pixels = list(quantized.getdata())
    assert set(pixels) == {0, 1, 2, 3}
    data = bytearray()
    for i in range(0, len(pixels), 4):
        a,b,c,d = pixels[i:i+4]
        data.append((a<<6)|(b<<4)|(c<<2)|d)
    assert len(data) == SIZE*SIZE//4
    header = ROOT/'src/images/YbxSleepLogo4.h'
    text = ('#pragma once\n#include <cstdint>\n\n'
            '// GENERATED by scripts/generate_ybx_sleep_logo.py from the YBX Companion brand geometry.\n'
            '// Pixel order: left-to-right, top-to-bottom; 2 bits per pixel, 0=black, 3=white.\n'
            f'constexpr int YBX_SLEEP_LOGO_SIZE = {SIZE};\n'
            'static const uint8_t YbxSleepLogo4[] = {\n')
    for i in range(0,len(data),20):
        text += '    '+', '.join(f'0x{v:02x}' for v in data[i:i+20])+',\n'
    header.write_text(text+'};\n')
    preview = Image.new('L',(SIZE,SIZE))
    preview.putdata([v*85 for v in pixels])
    preview.save(ROOT/'src/images/YbxSleepLogo4.png', optimize=True)
    print('Generated:', header, len(data),'bytes; four grayscale levels')

if __name__=='__main__':generate()
